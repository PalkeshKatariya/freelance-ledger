const CACHE = "total-berries-v5";
const ASSETS = [
  "./",
  "./index.html",
  "./styles.css?v=4.0",
  "./app.js?v=4.0",
  "./manifest.webmanifest",
  "./icon.svg"
];

// Skip waiting immediately so this service worker replaces any older one instantly
self.addEventListener("install", event => {
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE).then(cache => cache.addAll(ASSETS))
  );
});

// Delete ALL old caches and claim all clients immediately
self.addEventListener("activate", event => {
  event.waitUntil(
    caches.keys().then(keys => Promise.all(
      keys.filter(k => k !== CACHE).map(k => caches.delete(k))
    )).then(() => self.clients.claim())
  );
});

// Network-first strategy: always fetch fresh from network, fall back to cache only when offline
self.addEventListener("fetch", event => {
  if (event.request.method !== "GET") return;
  event.respondWith(
    fetch(event.request)
      .then(response => {
        if (response && response.status === 200) {
          const clone = response.clone();
          caches.open(CACHE).then(cache => cache.put(event.request, clone));
        }
        return response;
      })
      .catch(() => caches.match(event.request).then(hit => hit || caches.match("./index.html")))
  );
});
